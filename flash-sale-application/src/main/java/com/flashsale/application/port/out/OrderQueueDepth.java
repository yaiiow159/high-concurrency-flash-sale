package com.flashsale.application.port.out;

/**
 * 建單佇列的深度（ADR-0023）——單機記憶體級的閘門，與 {@link SoldOutMarker} 同型。
 *
 * <h2>為什麼是「讀快取值」而不是「問 Kafka」</h2>
 *
 * <p>熱路徑上只有 Redis 與 Kafka 各一次遠端呼叫，那是上限（CLAUDE.md 鐵則 2）。
 * 入場控制不能為了問「現在多塞」而多打一次。
 *
 * <p>因此拆成兩半：慢車道的排程每幾秒問一次 broker 並寫進記憶體，
 * 快車道只讀那個值——奈秒級、零 I/O。代價是指標有幾秒延遲，
 * 而尖峰前幾秒擋不住的量在可承受範圍內。
 */
public interface OrderQueueDepth {

    /**
     * 目前積壓的訊息數。
     *
     * <p>還沒量到任何值時回 0（而不是拋錯或回 -1）——
     * <b>沒有資料時不可以擋人</b>：入場控制失效的代價是「收太多」，
     * 而誤擋的代價是「合法的請求被拒絕」，後者嚴重得多。
     * 這與限流器 Redis 故障時 fail-open 是同一個判斷。
     */
    long backlog();

    /** 最近實測的建單速率（每秒）。尚無資料時回 0。 */
    double drainRatePerSecond();

    /**
     * 依目前積壓與速率推估的等待秒數；無法推估時回 {@code -1}。
     *
     * <p>回 -1 而不是 0：0 的意思是「不用等」，而「算不出來」不是那個意思。
     */
    long estimatedWaitSeconds();

    /**
     * 積壓是否已經超過可接受的等待時間。
     *
     * <p>閾值以<b>等待時間</b>而非訊息數表示——訊息數在消費端加機器之後
     * 就失去意義，而「使用者願意等幾分鐘」是一個可以跟產品討論的單位。
     */
    boolean isOverloaded();
}
