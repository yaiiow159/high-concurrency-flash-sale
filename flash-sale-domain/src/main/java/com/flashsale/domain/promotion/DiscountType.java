package com.flashsale.domain.promotion;

/**
 * 折扣的來源類型。
 *
 * <p>它同時決定<b>計算順序</b>（ADR-0013 決策 2）——順序不是實作細節，
 * 是業務決定：先打八折再減 100 與先減 100 再打八折，差距是 20 元。
 *
 * <p>列舉的宣告順序就是計算順序。這件事只在這裡是真的，
 * 別的地方不可以再寫一份順序。
 */
public enum DiscountType {

    /** 單品折扣：改變某一行的實付單價。 */
    ITEM_DISCOUNT,

    /** 訂單折扣：滿減、整單折扣，對折後小計計算。 */
    ORDER_DISCOUNT,

    /**
     * 優惠券。
     *
     * <p><b>排在訂單折扣之後</b>：滿減是商家活動，券是給特定人的補償或行銷。
     * 讓券先算會壓低小計、讓「滿千折百」的門檻更難達到——
     * 等於用券懲罰使用者。
     */
    COUPON,

    /** 運費折抵。最後算，因為免運門檻看的是折後金額。 */
    SHIPPING
}
