package com.flashsale.domain.notification;

/**
 * 通知類型。
 *
 * <h2>不是每個領域事件都值得通知使用者</h2>
 *
 * <p>系統目前有八個領域事件，這裡只收五個。判準是
 * <b>「使用者需要因為這件事做什麼，或它改變了他的預期」</b>：
 *
 * <ul>
 *   <li>{@code order.created} <b>不通知</b>。秒殺剛搶到的人正盯著畫面，
 *       通知他一件他已經知道的事沒有價值；更實際的是尖峰時每秒上萬筆建單，
 *       那會在我們正努力削峰的時刻自己造出第二波寫入</li>
 *   <li>{@code payment.succeeded} <b>不通知</b>。從買家的角度它與
 *       {@code order.paid} 是同一件事，兩個都發只會讓人收到兩封一樣的信</li>
 *   <li>{@code payment.refund-required} <b>不通知</b>。那是系統內部的競態補償，
 *       買家看不懂也不需要處理——它該進的是維運告警而不是收件匣</li>
 * </ul>
 *
 * <p>這條線鬆掉的後果是通知變成雜訊，然後使用者關掉全部通知，
 * 連真正重要的「已出貨」也一起看不到。
 */
public enum NotificationType {

    /** 付款成功。使用者需要知道錢收到了、接下來等出貨。 */
    ORDER_PAID,

    /** 已出貨。改變了預期——從「等出貨」變成「等收貨」，而且開始能追蹤物流。 */
    ORDER_SHIPPED,

    /** 已送達。是鑑賞期的起算點，使用者需要知道時間開始跑。 */
    ORDER_COMPLETED,

    /** 訂單已取消。多半是逾時未付款，使用者可能還在等著付款。 */
    ORDER_CANCELLED,

    /** 退款已送出。錢什麼時候會回到帳上是退貨流程裡最常被問的一件事。 */
    REFUND_SENT
}
